def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(ARTIFACT_ROOT / "data" / "example"))
    parser.add_argument("--seed", type=int, default=20250906)
    args = parser.parse_args(argv)

    out_dir = Path(args.out)
    if "example" not in out_dir.resolve().name.lower():
        # The watermark guard keys on the path. Writing synthetic data somewhere
        # that does not say "example" would defeat it.
        raise SystemExit(
            f"refusing to write synthetic data to {out_dir}: the directory name must "
            "contain 'example' so the watermark and macro guards can detect it."
        )
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(args.seed)

    print("Generating SYNTHETIC example data (nothing here was measured):")
    make_scenarios(rng, out_dir)
    make_ramp(rng, out_dir)
    make_microbench(rng, out_dir)
    make_controller_trace(rng, out_dir)
    print(f"\nWrote synthetic example data to {out_dir}")
    print("Every file carries a 'SYNTHETIC EXAMPLE DATA' header; figures built from")
    print("it are watermarked and generated macros are wrapped in \\SYNTHVAL.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
