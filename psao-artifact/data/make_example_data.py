def make_scenarios(rng, out_dir: Path):
    header = [
        "scenario", "environment", "run", "throughput_rps", "throughput_window",
        "latency_mean_ms", "latency_p50_ms", "latency_p90_ms", "latency_p95_ms",
        "latency_p99_ms", "latency_stdev_ms", "cpu_app_millicores",
        "cpu_sidecar_millicores", "cpu_ingress_millicores", "cpu_limit_millicores",
    ]
    rows, sample_rows = [], []

    for scenario, spec in SCENARIOS.items():
        mu, offset = spec["mu"], spec["offset"]
        for run in range(1, N_RUNS + 1):
            # Closed loop: VUs / (think + latency) is the fixed point. Two
            # iterations is plenty at these latencies.
            latency_s = 0.005
            for _ in range(6):
                lam = VUS / (THINK_S + latency_s)
                latency_s = md1_ms(lam, mu, offset) / 1000.0
            steady_rps = VUS / (THINK_S + latency_s)
            mean_ms = latency_s * 1000.0

            # Between-run variation: a few percent, which is what makes the
            # run-means family in stats_tests.py have anything to test.
            run_factor = 1.0 + rng.normal(0.0, 0.03)
            mean_ms *= run_factor

            # Per-request samples: lognormal with the target mean. Latency is
            # right-skewed, which is the reason stats_tests.py bothers with
            # Mann-Whitney and a median-difference interval.
            sigma = 0.35
            n_samples = 2000
            draws = rng.lognormal(mean=math.log(mean_ms) - sigma ** 2 / 2,
                                  sigma=sigma, size=n_samples)

            windows = {
                "steady": (steady_rps, draws),
                # The full profile includes ramps, so throughput over the whole
                # window is lower. This is the ambiguity amortized_cpu.py exists
                # to expose.
                "full": (steady_rps * STEADY_S / (WARMUP_S + STEADY_S + RAMPDOWN_S)
                         * 1.15, draws),
            }
            for window, (rps, values) in windows.items():
                rows.append([
                    scenario, ENVIRONMENT, run, fmt(rps, 3), window,
                    fmt(float(np.mean(values))), fmt(float(np.percentile(values, 50))),
                    fmt(float(np.percentile(values, 90))), fmt(float(np.percentile(values, 95))),
                    fmt(float(np.percentile(values, 99))), fmt(float(np.std(values, ddof=1))),
                    fmt(cpu_millicores(rps, mu, spec["verify_in"], "app"), 3),
                    fmt(cpu_millicores(rps, mu, spec["verify_in"], "sidecar"), 3),
                    fmt(cpu_millicores(rps, mu, spec["verify_in"], "ingress"), 3),
                    fmt(CPU_LIMIT_MILLICORES, 1),
                ])

            if scenario in DENSITY_SCENARIOS:
                for value in draws:
                    sample_rows.append([scenario, ENVIRONMENT, run, fmt(float(value))])

    write_csv(out_dir / "scenarios.csv", header, rows)
    write_csv(out_dir / "latency_samples.csv",
              ["scenario", "environment", "run", "latency_ms"], sample_rows)


