def make_microbench(rng, out_dir: Path):
    """Synthetic stage timings with the right ORDERING and rough magnitudes.

    Run `make microbench` for real numbers; this only lets the figure render.
    """
    header = ["algorithm", "stage", "payload_kb", "iterations",
              "mean_us", "p50_us", "p99_us"]
    # Round hand-picked base costs in microseconds.
    base = {
        ("HS256", "primitive_raw"): 1.2,
        ("HS256", "primitive_preparsed"): 1.6,
        ("HS256", "decode_only"): 3.0,
        ("HS256", "full_verify"): 6.4,
        ("RS256", "primitive_raw"): 28.0,
        ("RS256", "primitive_preparsed"): 30.0,
        ("RS256", "decode_only"): 3.0,
        ("RS256", "full_verify"): 40.0,
    }
    payload_scaling = {0.5: 1.00, 2.0: 1.35, 4.0: 1.85}
    rows = []
    for (algorithm, stage), cost in base.items():
        for payload, scale in payload_scaling.items():
            # Only the size-dependent stages scale with the payload; the RSA
            # exponentiation does not care how long the message was.
            grows = stage in ("decode_only", "full_verify") or algorithm == "HS256"
            mean = cost * (scale if grows else 1.0) * (1.0 + rng.normal(0.0, 0.01))
            rows.append([
                algorithm, stage, payload, 1_000_000,
                fmt(mean, 6), fmt(mean * 0.96, 6), fmt(mean * 1.9, 6),
            ])
    rows.sort(key=lambda r: (r[0], r[1], r[2]))
    write_csv(out_dir / "microbench.csv", header, rows)


