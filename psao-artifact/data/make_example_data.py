def _controller_observation_rows(rng, mu_app, mu_side, offset, poll_s, duration_s,
                                 sidecar_windows):
    """Observation columns for the synthetic controller run.

    `sidecar_windows` is a list of (start_s, end_s) during which verification is
    assumed to be running in the sidecar, which raises the effective service rate
    from mu_app to mu_side. That is what makes latency flatten after an offload.
    """
    rows = []
    t0 = 1_757_000_000.0  # a fixed, obviously round epoch: this is not a real run
    n = int(duration_s / poll_s)
    for i in range(n):
        t_rel = i * poll_s
        fraction = t_rel / duration_s
        # Trapezoid: up for 40% of the run, hold for 20%, down for 40%.
        if fraction < 0.4:
            lam = 20.0 + (460.0 - 20.0) * (fraction / 0.4)
        elif fraction < 0.6:
            lam = 460.0
        else:
            lam = 460.0 - (460.0 - 20.0) * ((fraction - 0.6) / 0.4)
        # Noise large enough that the hysteresis has something to suppress.
        lam = max(1.0, lam * (1.0 + rng.normal(0.0, 0.035)))

        in_sidecar = any(a <= t_rel < b for a, b in sidecar_windows)
        mu = mu_side if in_sidecar else mu_app
        rho = min(0.999, lam / mu)
        rows.append([
            fmt(t0 + t_rel, 3), fmt(t_rel, 3), fmt(lam, 3),
            fmt(0.20 + 1000.0 * rho / (2.0 * mu * max(1e-6, 1.0 - rho))),
            fmt(mu, 3), fmt(rho, 4), fmt(md1_ms(lam, mu, offset)),
            "app", "hold", "", "synthetic-observation",
        ])
    return rows


def _run_controller(seed_path: Path, trace_path: Path):
    command = [
        sys.executable, str(ARTIFACT_ROOT / "controller" / "psao_controller.py"),
        "--config", str(ARTIFACT_ROOT / "controller" / "config.yaml"),
        "--dry-run", "--replay", str(seed_path), "--replay-speed", "0",
        "--out", str(trace_path), "--log-level", "WARNING",
    ]
    completed = subprocess.run(command, capture_output=True, text=True, check=False)
    if completed.returncode != 0 or not trace_path.exists():
        sys.stderr.write(completed.stdout + completed.stderr)
        raise SystemExit(
            "the controller failed on the synthetic observations, so no example "
            "controller_trace.csv was written. Fix the controller rather than "
            "hand-writing a trace."
        )
    return command


def _sidecar_windows(trace_path: Path, duration_s: float):
    """Read back the intervals the controller spent in sidecar mode."""
    with trace_path.open(newline="") as fh:
        rows = list(csv.DictReader(line for line in fh if not line.startswith("#")))
    windows, start = [], None
    for row in rows:
        t_rel = float(row["t_rel_s"])
        if row["mode"] == "sidecar" and start is None:
            start = t_rel
        elif row["mode"] != "sidecar" and start is not None:
            windows.append((start, t_rel))
            start = None
    if start is not None:
        windows.append((start, duration_s))
    return windows


def make_controller_trace(rng, out_dir: Path, poll_s: float = 2.0,
                          duration_s: float = 1800.0, max_passes: int = 4):
    """Generate the observation columns, then run the REAL controller over them.

    The load profile rises past the trigger, holds, and falls back through the
    revert band, so the resulting trace contains an offload, a revert, and the
    suppressed flaps the hysteresis produced along the way.

    TWO-WAY COUPLING, RESOLVED BY ITERATION
    ---------------------------------------
    Offloading verification to the sidecar raises the application's effective
    service rate, which lowers latency, which changes what the controller
    observes next. A single forward pass cannot represent that: the observations
    would still be on the pre-offload service curve after the offload, and the
    example figure would show no post-offload flattening at all.

    So we iterate to a fixed point. Pass 1 assumes no offload; the controller
    tells us when it offloaded; pass 2 regenerates the observations with the
    higher service rate inside that window; repeat until the windows stop moving
    (usually two passes). The result is a self-consistent SYNTHETIC scenario, not
    a simulation anybody should cite -- it exists so the figure has the shape a
    real run would have.
    """
    app_spec = SCENARIOS["S5"]         # verification on the event loop
    sidecar_spec = SCENARIOS["S7"]     # verification in the Envoy sidecar
    mu_app, offset = app_spec["mu"], app_spec["offset"]
    mu_side = sidecar_spec["mu"]

    seed_path = out_dir / ".controller_observations.synthetic.csv"
    trace_path = out_dir / "controller_trace.csv"
    header = ["t_unix", "t_rel_s", "lambda_rps", "eventloop_lag_p99_ms", "mu_eff_rps",
              "rho", "latency_mean_ms", "mode", "decision", "actuation_latency_ms",
              "trigger_reason"]

    windows = []
    command = None
    for attempt in range(max_passes):
        # Same seed each pass so the load profile itself does not move between
        # passes; only the service rate inside the offload windows changes.
        pass_rng = np.random.default_rng(20250906 + 991)
        rows = _controller_observation_rows(pass_rng, mu_app, mu_side, offset,
                                            poll_s, duration_s, windows)
        seed_path.parent.mkdir(parents=True, exist_ok=True)
        with seed_path.open("w", newline="") as fh:
            fh.write(BANNER)
            writer = csv.writer(fh)
            writer.writerow(header)
            writer.writerows(rows)

        command = _run_controller(seed_path, trace_path)
        new_windows = _sidecar_windows(trace_path, duration_s)
        print(f"  pass {attempt + 1}: sidecar windows = "
              + (", ".join(f"{a:.0f}-{b:.0f}s" for a, b in new_windows) or "none"))
        if new_windows == windows:
            break
        windows = new_windows

    print("  produced by the real controller:")
    print("    " + " ".join(command[1:]))

    # Prepend the synthetic banner: the controller writes a plain CSV, and every
    # file in data/example must declare itself.
    body = trace_path.read_text()
    trace_path.write_text(BANNER + body)
    seed_path.unlink()
    print(f"  {trace_path}  ({body.count(chr(10)) - 1} rows)")


