#!/usr/bin/env python3
"""make_example_data.py -- generate SYNTHETIC example CSVs.

READ THIS FIRST
===============
Everything this script writes is FABRICATED. It exists so that `make all` runs
end to end on a laptop with no Kubernetes cluster, exercising every loader,
every fit, every test and every figure. It is a pipeline test, not data.

Nothing here was measured. The numbers come from closed-form queueing formulas
with round, obviously-chosen constants and a fixed random seed. They are
deliberately smooth and deliberately reproducible, which is exactly what real
measurements are not.

Three independent guards keep this output out of a paper:

  1. Every file begins with a comment line containing "SYNTHETIC EXAMPLE DATA",
     which analysis/io.py detects.
  2. The output directory is named `example`, which the same guard also detects.
  3. Figures rendered from it carry a diagonal watermark, and generated LaTeX
     macros are wrapped in \\SYNTHVAL so they typeset in red with a dagger.

The controller trace is not fabricated by this script beyond its inputs: the
observation columns are generated here, and the decision, mode and
actuation_latency_ms columns are produced by running the REAL controller over
them in --dry-run --replay. That keeps one implementation of the policy in the
repository rather than two that can disagree.

Usage:  python data/make_example_data.py [--out data/example] [--seed 20250906]
"""
from __future__ import annotations

import argparse
import csv
import math
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

ARTIFACT_ROOT = Path(__file__).resolve().parent.parent

BANNER = (
    "# SYNTHETIC EXAMPLE DATA - NOT FOR PUBLICATION. Generated by "
    "data/make_example_data.py from closed-form queueing formulas with a fixed "
    "seed. Nothing in this file was measured.\n"
)

# --- synthetic scenario constants -------------------------------------------
# Round numbers, chosen by hand to give the pipeline something with the right
# shape: monotone cost as security layers are added, an elbow inside the ramp,
# S7 (sidecar offload) cheaper on the application than S5, S9 (cluster) faster
# but no cheaper per request. They are illustrative, not representative.
SCENARIOS = {
    #        mu (rps)  network offset (ms)  verify cost carried by
    "S1": dict(mu=1000.0, offset=2.00, verify_in="none"),
    "S2": dict(mu=900.0,  offset=2.40, verify_in="none"),
    "S3": dict(mu=800.0,  offset=2.80, verify_in="none"),
    "S4": dict(mu=700.0,  offset=2.20, verify_in="app"),
    "S5": dict(mu=600.0,  offset=2.90, verify_in="app"),
    "S6": dict(mu=380.0,  offset=2.90, verify_in="app"),
    "S7": dict(mu=780.0,  offset=3.20, verify_in="sidecar"),
    "S8": dict(mu=820.0,  offset=2.90, verify_in="app"),
    "S9": dict(mu=1900.0, offset=2.90, verify_in="app"),
}

RAMP_SCENARIOS = ["S1", "S3", "S5"]
DENSITY_SCENARIOS = ["S1", "S5", "S6", "S7"]
ENVIRONMENT = "local"
N_RUNS = 3
N_RAMP_SWEEPS = 3
CPU_LIMIT_MILLICORES = 1000.0
VUS = 100
THINK_S = 1.0
WARMUP_S, STEADY_S, RAMPDOWN_S = 20.0, 60.0, 10.0


def md1_ms(lam: float, mu: float, offset_ms: float) -> float:
    """M/D/1 mean response time in ms, plus a constant network offset."""
    rho = lam / mu
    if rho >= 1.0:
        return math.inf
    return 1000.0 * (1.0 / mu + rho / (2.0 * mu * (1.0 - rho))) + offset_ms


def cpu_millicores(lam: float, mu: float, verify_in: str, component: str) -> float:
    """Synthetic CPU: service time times rate, plus a fixed idle floor.

    The verification cost is carried by whichever component the scenario says
    carries it, which is the whole point of the S5/S7 comparison.
    """
    service_ms = 1000.0 / mu
    verify_ms = 0.35 if verify_in != "none" else 0.0
    if component == "app":
        base = service_ms - (verify_ms if verify_in == "sidecar" else 0.0)
        return 40.0 + lam * max(base, 0.05)
    if component == "sidecar":
        base = 0.55 + (verify_ms if verify_in == "sidecar" else 0.0)
        return 20.0 + lam * base
    return 15.0 + lam * 0.40  # ingress


def write_csv(path: Path, header: list[str], rows: list[list]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as fh:
        fh.write(BANNER)
        writer = csv.writer(fh)
        writer.writerow(header)
        writer.writerows(rows)
    print(f"  {path}  ({len(rows)} rows)")


def fmt(value: float, digits: int = 4) -> str:
    return "" if value is None or not math.isfinite(value) else f"{value:.{digits}f}"


