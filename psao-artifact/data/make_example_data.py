def make_ramp(rng, out_dir: Path, max_rps: int = 400, step_rps: int = 20):
    header = ["scenario", "environment", "target_rps", "achieved_rps",
              "latency_mean_ms", "latency_p99_ms", "cpu_app_millicores",
              "cpu_sidecar_millicores", "eventloop_lag_p99_ms"]
    rows = []
    for scenario in RAMP_SCENARIOS:
        spec = SCENARIOS[scenario]
        mu, offset = spec["mu"], spec["offset"]
        for _sweep in range(N_RAMP_SWEEPS):
            for target in range(step_rps, max_rps + 1, step_rps):
                # Past ~98% utilisation the generator cannot keep up; achieved
                # falls below target, and elbow_fit.py excludes those steps.
                achieved = min(target, mu * 0.98) * (1.0 + rng.normal(0.0, 0.004))
                mean_ms = md1_ms(achieved, mu, offset) * (1.0 + rng.normal(0.0, 0.02))
                if not math.isfinite(mean_ms):
                    continue
                rho = achieved / mu
                rows.append([
                    scenario, ENVIRONMENT, target, fmt(achieved, 3),
                    fmt(mean_ms), fmt(mean_ms * (2.2 + 3.0 * rho)),
                    fmt(cpu_millicores(achieved, mu, spec["verify_in"], "app"), 3),
                    fmt(cpu_millicores(achieved, mu, spec["verify_in"], "sidecar"), 3),
                    # Event-loop lag grows sharply with utilisation: the M/D/1
                    # waiting term is the natural shape to borrow.
                    fmt(0.20 + 1000.0 * rho / (2.0 * mu * max(1e-6, 1.0 - rho))),
                ])
    write_csv(out_dir / "openloop_ramp.csv", header, rows)


